// Folds what companions learned while playing into the shipped network, so it is part of the model and not only of one save.
//   node tools/policy/bake.js <code or file> [<code or file> ...]
// A code is the text from the game (Gear, Party, Show learned data: "DWPOLICY1:..."); a file holds one or more codes, one per line.
// The learned preferences (a bias per class and move, in units of the network's gap between its first and second choice) from every
// code are averaged, weighted by the number of fights, and added to the network's per-class output bias (weights.cb). After baking,
// forget the learned data in the game (Party panel), or it would be counted twice on top of the new model.
const fs = require('fs'), path = require('path');
const file = process.env.POLICY_FILE || path.join(__dirname, '../../js/policy_weights.js');            // (the tests bake into a copy)
const Policy = require('../../js/policy.js');
const src = fs.readFileSync(file, 'utf8');
const w = new Function(src.replace(/^[^]*?const DW_POLICY =/, 'return ').replace(/;\s*$/, ';'))();
const codes = [];
for (const arg of process.argv.slice(2)) {
  const t = fs.existsSync(arg) ? fs.readFileSync(arg, 'utf8') : arg;
  for (const line of t.split(/\s+/)) if (line.startsWith('DWPOLICY1:')) codes.push(line);
}
if (!codes.length) { console.error('usage: bake.js <DWPOLICY1:... code | file with codes> ...'); process.exit(1); }
const data = codes.map(c => JSON.parse(Buffer.from(c.slice('DWPOLICY1:'.length), 'base64').toString('utf8')));
const total = data.reduce((s, d) => s + (d.n || 0), 0);
if (total < 1) { console.error('no fights in those codes'); process.exit(1); }
const unit = (w.meta.gap || 4) * Policy.Learner.params.EXPLORE;
w.cb = w.cb || {}; const before = {};
for (const c of Policy.CLS) {
  w.cb[c] = w.cb[c] || new Array(Policy.ACTIONS.length).fill(0); before[c] = w.cb[c].slice();
  for (let k = 0; k < Policy.ACTIONS.length; k++) {
    let m = 0; for (const d of data) m += ((d.bias && d.bias[c] ? d.bias[c][k] : 0) * (d.n || 0)) / total;
    w.cb[c][k] = Math.round((w.cb[c][k] + unit * m) * 1e4) / 1e4;
  }
}
w.meta.baked = (w.meta.baked || 0) + total;
fs.writeFileSync(file, '// Generated by tools/policy/train.js (imitation of the rules, then evolution strategies in tools/policy/sim.js), with learned preferences folded in by tools/policy/bake.js. Do not edit by hand.\nconst DW_POLICY = ' + JSON.stringify(w) + ';\n');
console.log(`baked ${total} fights from ${codes.length} code(s); changes per class (logit units):`);
for (const c of Policy.CLS) console.log('  ' + c.padEnd(8), w.cb[c].map((x, k) => (x - before[c][k]).toFixed(2)).join(' '), '  [' + Policy.ACTIONS.join(' ') + ']');
