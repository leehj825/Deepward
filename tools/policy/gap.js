// Measures the network's typical gap between its first and second legal choice (in logits) and stores it as meta.gap in
// js/policy_weights.js. The run-time learner (Policy.Learner) uses it as the unit of its preferences and its exploration.
//   node tools/policy/gap.js
const fs = require('fs'), path = require('path');
const { run, makeScenario, Policy } = require('./sim.js');
const file = path.join(__dirname, '../../js/policy_weights.js');
function update() {
  const src = fs.readFileSync(file, 'utf8'), w = new Function(src.replace(/^[^]*?const DW_POLICY =/, 'return ').replace(/;\s*$/, ';'))();
  const gaps = [];
  for (let i = 0; i < 150; i++) run(makeScenario(300000 + i), s => {
    const o = Policy.forward(w, Policy.encode(s)), m = Policy.legal(s), v = o.filter((_, k) => m[k]).sort((a, b) => b - a);
    if (v.length > 1) gaps.push(v[0] - v[1]);
    return Policy.classic(s);
  });
  gaps.sort((a, b) => a - b); const med = gaps[Math.floor(gaps.length / 2)];
  w.meta = Object.assign(w.meta || {}, { gap: +med.toFixed(2) });
  fs.writeFileSync(file, '// Generated by tools/policy/train.js (imitation of the rules, then evolution strategies in tools/policy/sim.js). Do not edit by hand.\nconst DW_POLICY = ' + JSON.stringify(w) + ';\n');
  return med;
}
module.exports = { update };
if (require.main === module) console.log('median gap between the first and second choice:', update().toFixed(2));
