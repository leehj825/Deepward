#!/usr/bin/env node
// Turns the mutant's Mixamo clips (the Creature Pack) into js/anims_mutant.js, added to DW_ANIMS at load.
// 1. Retarget the FBX files with Nightfall Settlement's converter, using the clip list in tools/creature_want.json:
//      WANT_FILE=tools/creature_want.json OUT_FILE=/tmp/mutant_clips.js \
//        node ../Nightfall-Settlement/tools/retarget_mixamo.js <three@0.128 dir> <folder with the pack's .fbx files>
// 2. node tools/extract_creature.js /tmp/mutant_clips.js
// Like tools/extract_anims.js, every rotation is mirrored back across X (Nightfall mirrors Mixamo for its sword hand).
// Jump attacks hit as the creature lands (the lowest pelvis after its highest), not at the fastest hand.
const fs = require('fs'), path = require('path');
const src = process.argv[2];
if (!src) { console.error('usage: extract_creature.js <retargeted clips .js>'); process.exit(1); }
const A = new Function(fs.readFileSync(src, 'utf8') + ';return MIXAMO_CLIPS')();
const r3 = v => Math.round(v * 1000) / 1000, out = {};
for (const [name, c] of Object.entries(A)) {
  const t = {};
  for (const [bone, frames] of Object.entries(c.t)) t[bone] = (bone === 'hipsY' || bone === 'hipsZ') ? frames.map(r3) : frames.map(v => [r3(v[0]), r3(-v[1]), r3(-v[2])]);
  let hit = c.hit;
  if (/JumpAttack/.test(name)) { const ys = t.hipsY, top = ys.indexOf(Math.max(...ys)), low = Math.min(...ys.slice(top)); for (let i = top; i < ys.length; i++) if (ys[i] <= low + 0.03) { hit = r3(i / c.n); break; } }
  out[name] = { d: c.d, n: c.n, loop: !!c.loop, hit, t };
}
const file = path.join(__dirname, '..', 'js', 'anims_mutant.js');
fs.writeFileSync(file, '// Generated by tools/extract_creature.js from the Creature Pack (Mixamo mutant clips, retargeted and mirrored to this rig). Do not edit by hand.\n' +
  'Object.assign(DW_ANIMS, ' + JSON.stringify(out) + ');\n');
console.log('wrote', path.relative(process.cwd(), file), Math.round(fs.statSync(file).size / 1024) + ' KB,', Object.keys(out).length, 'clips:', Object.entries(out).map(([k, c]) => k + '@' + c.hit).join(' '));
