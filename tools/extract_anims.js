#!/usr/bin/env node
// Copies motion-capture clips from Nightfall Settlement (js/anims.js and js/anims_lib.js, retargeted from Mixamo there)
// into js/anims.js here as DW_ANIMS.
//   node tools/extract_anims.js <path to Nightfall-Settlement>
// Nightfall's rig holds the sword in its +X hand and mirrors Mixamo to suit; Deepward holds it in the -X hand (the
// character's true right when facing +Z), so every rotation is mirrored back across X: (x, y, z) -> (x, -y, -z).
// Bone names are unchanged: 'R' bones carry the sword arm and the right leg in both games.
const fs = require('fs'), path = require('path');
const src = process.argv[2];
if (!src) { console.error('usage: extract_anims.js <Nightfall-Settlement dir>'); process.exit(1); }
const load = (f, v) => new Function(fs.readFileSync(path.join(src, 'js', f), 'utf8') + ';return ' + v)();
const A = load('anims.js', 'MIXAMO_CLIPS'), L = load('anims_lib.js', 'MIXAMO_LIB');

// Deepward name -> [source table, source name]
const WANT = {
  // sword and shield
  idle: [A, 'ssIdle'], idleCalm: [A, 'ssIdleCalm'], walkCalm: [A, 'walk'], runCalm: [A, 'run'], walk: [A, 'ssWalk'], walkB: [A, 'ssWalkB'], run: [A, 'ssRun'], runB: [A, 'ssRunB'],
  strafeWalkN: [A, 'ssStrafeNW'], strafeWalkP: [A, 'ssStrafePW'], strafeRunN: [A, 'ssStrafeN'], strafeRunP: [A, 'ssStrafeP'],
  attack1: [A, 'ssAttack1'], attack2: [A, 'ssAttack2'], attack3: [A, 'ssAttack3'], attackJump: [A, 'ssAttack4'],
  slash1: [L, 'ss_sword_and_shield_slash'], slash3: [L, 'ss_sword_and_shield_slash_3'], slash5: [L, 'ss_sword_and_shield_slash_5'], kick: [L, 'ss_sword_and_shield_kick'],
  block: [A, 'ssBlock'], blockIdle: [L, 'ss_sword_and_shield_block_idle'],
  impact: [A, 'ssImpact'], impact2: [A, 'ssImpact2'], die: [A, 'die'], die2: [A, 'die2'],
  dive: [L, 'bow_standing_dive_forward'], dodgeB: [A, 'bowDodgeB'], dodgeP: [A, 'bowDodgeP'], dodgeN: [A, 'bowDodgeN'],
  // great sword (the brute's two-handed club)
  gsIdle: [A, 'gsIdle'], gsWalk: [A, 'gsWalk'], gsWalkB: [A, 'gsWalkB'], gsRun: [A, 'gsRun'], gsRunB: [A, 'gsRunB'],
  gsStrafeWalkN: [A, 'gsStrafeNW'], gsStrafeWalkP: [A, 'gsStrafePW'], gsStrafeRunN: [A, 'gsStrafeN'], gsStrafeRunP: [A, 'gsStrafeP'],
  gsBlock: [A, 'gsBlock'], gsSpin: [A, 'gsAttack4'],
  // archer
  shoot: [A, 'bowDraw'],
  gsAttack: [A, 'gsAttack1'], gsSlash: [A, 'gsAttack2'], gsSlash5: [A, 'gsAttack3'], gsJumpAttack: [L, 'gs_great_sword_jump_attack'],
  gsImpact: [A, 'gsImpact'], gsDie: [A, 'dieGs'],
  // everyday postures for the people of the Hold (and the hero at ease there)
  idleEase: [L, 'loco_idle'], idleLook: [L, 'bow_standing_idle_02_looking'], idleExamine: [L, 'bow_standing_idle_03_examine'], idleUnarmed: [L, 'bow_unarmed_idle_01'],
  idleShift: [L, 'ss_sword_and_shield_idle_2'], idleAlert: [L, 'ss_sword_and_shield_idle_4'], idleHold: [L, 'farm_holding_idle'],
  kneel: [L, 'farm_kneeling_idle'], seatWork: [L, 'farm_cow_milking'], pullPlant: [L, 'farm_pull_plant'], plant: [L, 'farm_plant_a_plant'],
};

const r3 = v => Math.round(v * 1000) / 1000;
const out = {};
for (const [name, [table, key]] of Object.entries(WANT)) {
  const c = table[key];
  if (!c) { console.error('missing clip', key); process.exit(1); }
  const t = {};
  for (const [bone, frames] of Object.entries(c.t)) {
    t[bone] = (bone === 'hipsY' || bone === 'hipsZ') ? frames.map(r3) : frames.map(v => [r3(v[0]), r3(-v[1]), r3(-v[2])]);
  }
  out[name] = { d: c.d, n: c.n, loop: !!c.loop, hit: c.hit, t };
}
const file = path.join(__dirname, '..', 'js', 'anims.js');
fs.writeFileSync(file, '// Generated by tools/extract_anims.js from Nightfall Settlement\'s Mixamo clips (mirrored to this rig). Do not edit by hand.\n' +
  '// Per clip: d = seconds, n = frames - 1, hit = share of the clip at the moment of impact, t = per-bone Euler XYZ per frame, hipsY / hipsZ = pelvis height and forward shift.\n' +
  'const DW_ANIMS = ' + JSON.stringify(out) + ';\n');
console.log('wrote', path.relative(process.cwd(), file), Math.round(fs.statSync(file).size / 1024) + ' KB,', Object.keys(out).length, 'clips');
