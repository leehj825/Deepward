#!/usr/bin/env node
// Turns the Pro Magic Pack (Mixamo) into js/anims_magic.js, added to DW_ANIMS at load: the caster stance (idle, walk, run,
// block, hit reactions, deaths) and the spell moves of the mage and the cleric.
// 1. Retarget the FBX files with Nightfall Settlement's converter in library mode (every clip of the folder 'magic'):
//      LIB=1 OUT_FILE=/tmp/magic_lib.js node ../Nightfall-Settlement/tools/retarget_mixamo.js <three@0.128 dir> <folder 'magic' with the pack's .fbx files>
// 2. node tools/extract_magic.js /tmp/magic_lib.js
// Like tools/extract_anims.js, every rotation is mirrored back across X. The spell clips are long and slow, so each is cut to
// the second before its moment of impact and half a second after (the rig time-warps the rest onto the game's own timings).
const fs = require('fs'), path = require('path');
const src = process.argv[2];
if (!src) { console.error('usage: extract_magic.js <retargeted library .js>'); process.exit(1); }
const L = new Function(fs.readFileSync(src, 'utf8') + ';return MIXAMO_LIB')();

// Deepward name -> [library name, loop?, trim?]
const WANT = {
  mgIdle: ['standing_idle', true], mgWalk: ['standing_walk_forward', true], mgWalkB: ['standing_walk_back', true], mgWalkN: ['standing_walk_left', true], mgWalkP: ['standing_walk_right', true],
  mgRun: ['standing_run_forward', true], mgRunB: ['standing_run_back', true], mgRunN: ['standing_run_left', true], mgRunP: ['standing_run_right', true],
  mgBlock: ['standing_block_idle', true], mgImpact: ['standing_react_small_from_front'], mgImpact2: ['standing_react_large_from_front'],
  mgDie: ['standing_react_death_backward', false, 2.6], mgDie2: ['standing_react_death_forward', false, 2.6],
  // the mage's staff (two hands): a bolt, a variation, a fireball, a nova
  mgBolt: ['standing_2h_magic_attack_01', false, 'cut'], mgBolt2: ['standing_2h_magic_attack_04', false, 'cut'], mgFire: ['standing_2h_magic_area_attack_01', false, 'cut'], mgNova: ['standing_2h_magic_area_attack_02', false, 'cut'],
  // the cleric's scepter (one hand): holy bolt, single heal; and two hands for the blessing and the sanctuary
  mgHoly: ['standing_1h_magic_attack_01', false, 'cut'], mgHeal: ['standing_1h_cast_spell_01', false, 'cut'], mgBless: ['standing_2h_cast_spell_01', false, 'cut'], mgSanct: ['standing_2h_magic_attack_05', false, 'cut'],
};
const r3 = v => Math.round(v * 1000) / 1000, out = {};
for (const [name, [key, loop, trim]] of Object.entries(WANT)) {
  const lib = Object.keys(L).find(k => k === 'magic_' + key);
  const c = L[lib];
  if (!c) { console.error('missing clip', key); process.exit(1); }
  const fps = c.n / c.d, t = {};
  let a = 0, b = c.n;
  if (trim === 'cut') {                                            // from 1 s before the hit to 0.5 s after it
    const h = Math.round(c.hit * c.n); a = Math.max(0, h - Math.round(1.0 * fps)); b = Math.min(c.n, h + Math.round(0.5 * fps));
  } else if (typeof trim === 'number') b = Math.min(c.n, Math.round(trim * fps));
  for (const [bone, frames] of Object.entries(c.t)) {
    const f = frames.slice(a, b + 1);
    t[bone] = (bone === 'hipsY' || bone === 'hipsZ') ? f.map(r3) : f.map(v => [r3(v[0]), r3(-v[1]), r3(-v[2])]);
  }
  const n = b - a;
  out[name] = { d: r3(n / fps), n, loop: !!loop, hit: r3(Math.min(1, Math.max(0, (c.hit * c.n - a) / n))), t };
}
const file = path.join(__dirname, '..', 'js', 'anims_magic.js');
fs.writeFileSync(file, '// Generated by tools/extract_magic.js from the Pro Magic Pack (Mixamo, retargeted and mirrored to this rig). Do not edit by hand.\n' +
  'Object.assign(DW_ANIMS, ' + JSON.stringify(out) + ');\n');
console.log('wrote', path.relative(process.cwd(), file), Math.round(fs.statSync(file).size / 1024) + ' KB,', Object.keys(out).length, 'clips:', Object.entries(out).map(([k, c]) => k + '@' + c.hit).join(' '));
